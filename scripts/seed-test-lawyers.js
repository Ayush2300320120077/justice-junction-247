async function seed() {
  try {
    console.log('🔌 Connecting to MongoDB...');
    await mongoose.connect(MONGODB_URI);
    console.log('✅ Connected.\n');

    // Clean up any previously seeded test lawyers (by email pattern)
    const testEmails = testLawyers.map(l => l.email);
    const existingUsers = await User.find({ email: { $in: testEmails } });
    if (existingUsers.length > 0) {
      const userIds = existingUsers.map(u => u._id);
      await Lawyer.deleteMany({ user: { $in: userIds } });
      await User.deleteMany({ _id: { $in: userIds } });
      console.log(`🧹 Cleaned ${existingUsers.length} previously seeded test profiles.\n`);
    }

    let created = 0;
    for (const data of testLawyers) {
      // 1) Create User
      const user = new User({
        name: data.name,
        email: data.email,
        password: 'LawyerTest@2026',   // hashed by pre-save hook
        role: 'lawyer',
        phone: data.phone,
        city: data.city,
        state: data.state,
      });
      await user.save();

      // 2) Create Lawyer profile
      const lawyer = new Lawyer({
        user: user._id,
        name: data.name,
        email: data.email,
        phone: data.phone,
        barRegistrationNumber: data.barReg,
        specializations: data.specializations,
        experience: data.experience,
        experienceLevel: data.experienceLevel,
        city: data.city,
        state: data.state,
        pincode: data.pincode,
        courts: data.courts,
        consultationFee: data.consultationFee,
        bio: data.bio,
        languages: data.languages,
        isVerified: true,
        isAvailable: true,
        averageRating: data.averageRating,
        totalReviews: data.totalReviews,
        totalCases: data.totalCases,
        subscription: data.subscription,
        consultationModes: data.consultationModes,
        availableDays: data.availableDays,
        availableTimeFrom: data.availableTimeFrom,
        availableTimeTo: data.availableTimeTo,
        gender: data.gender,
        barCouncilState: data.barCouncilState,
        yearOfEnrollment: data.yearOfEnrollment,
        designation: data.designation,
        currentFirm: data.currentFirm || '',
      });
      await lawyer.save();

      created++;
      console.log(`  ✔ ${data.name} — ${data.city} — ${data.specializations.join(', ')}`);
    }

    console.log(`\n🎉 Successfully seeded ${created} lawyer profiles!`);
    console.log('   They are all isVerified: true and will appear in /search results.\n');
    process.exit(0);
  } catch (err) {
    console.error('❌ Seeding failed:', err.message);
    if (err.code === 11000) {
      console.error('   Duplicate key error — a user or lawyer with the same email/barReg already exists.');
      console.error('   Run the script again to auto-clean and re-seed.');
    }
    process.exit(1);
  }
}

seed();
